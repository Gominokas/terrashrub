//! `tesh build <env>` (design v0.2 §7.4): assemble `output/<env>/`
//! from land and the env's shrubs.
//!
//! Phase 1 handles raw `.tf` files only: files are layered in
//! application order (design v0.2 §6.1) — land first, then each shrub
//! in the order `env.toml` lists them — and a file from a later layer
//! replaces a same-named file from an earlier one. Every generated
//! file carries a provenance header (design v0.2 §8.4) naming all of
//! its sources. The output is deterministic: no timestamps, sorted
//! file order, and the output directory is regenerated from scratch
//! on every build.

use std::collections::BTreeMap;
use std::path::PathBuf;

use crate::error::{Error, Result};
use crate::project::{Project, sorted_tf_files};

#[derive(Debug)]
pub struct BuiltFile {
    pub name: String,
    /// Source paths relative to the project root, in application order.
    pub sources: Vec<String>,
}

struct LayeredFile {
    content: String,
    sources: Vec<String>,
}

pub fn build(project: &Project, env_name: &str) -> Result<Vec<BuiltFile>> {
    let env = project.envs.get(env_name).ok_or_else(|| {
        Error::new(format!(
            "env {env_name:?} not found (no envs/{env_name}/env.toml)"
        ))
    })?;

    // Design v0.2 §8.1: the execution context must be explicit.
    let missing = env.config.context.missing_fields();
    if !missing.is_empty() {
        return Err(Error::new(format!(
            "env {env_name:?}: context is incomplete, missing: {} (design v0.2 §8.1)",
            missing.join(", ")
        )));
    }

    let land_dir = project.land_dir();
    if !land_dir.is_dir() {
        return Err(Error::new(format!(
            "land/ directory not found in {}",
            project.root.display()
        )));
    }

    // Layers in application order: land, then shrubs as listed.
    let mut layers: Vec<(String, PathBuf)> = vec![("land".to_string(), land_dir)];
    for shrub_name in &env.config.shrubs {
        let shrub = project.shrubs.get(shrub_name).ok_or_else(|| {
            Error::new(format!(
                "env {env_name:?}: shrub {shrub_name:?} is listed in env.toml but shrubs/{shrub_name}/ does not exist"
            ))
        })?;
        layers.push((format!("shrubs/{shrub_name}"), shrub.dir.clone()));
    }

    let mut files: BTreeMap<String, LayeredFile> = BTreeMap::new();
    for (layer_label, dir) in &layers {
        for path in sorted_tf_files(dir)? {
            let file_name = path
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let content = std::fs::read_to_string(&path).map_err(|e| {
                Error::new(format!("cannot read {}: {e}", path.display()))
            })?;
            let source = format!("{layer_label}/{file_name}");
            let entry = files
                .entry(file_name)
                .or_insert_with(|| LayeredFile {
                    content: String::new(),
                    sources: Vec::new(),
                });
            entry.content = content;
            entry.sources.push(source);
        }
    }

    // Regenerate the output directory from scratch (design v0.2 §8.4:
    // output is disposable and regenerable; hand edits are lost).
    let out_dir = project.output_dir().join(env_name);
    if out_dir.exists() {
        std::fs::remove_dir_all(&out_dir).map_err(|e| {
            Error::new(format!(
                "cannot clean {}: {e}",
                out_dir.display()
            ))
        })?;
    }
    std::fs::create_dir_all(&out_dir).map_err(|e| {
        Error::new(format!("cannot create {}: {e}", out_dir.display()))
    })?;

    let mut built = Vec::new();
    for (name, file) in &files {
        let mut text = String::new();
        text.push_str(&format!(
            "# Generated by `tesh build {env_name}`. Do not edit; regenerate instead.\n"
        ));
        if file.sources.len() == 1 {
            text.push_str(&format!("# Source: {}\n", file.sources[0]));
        } else {
            text.push_str(&format!(
                "# Sources (applied in order; last wins): {}\n",
                file.sources.join(", ")
            ));
        }
        text.push_str(&file.content);
        if !text.ends_with('\n') {
            text.push('\n');
        }
        std::fs::write(out_dir.join(name), text).map_err(|e| {
            Error::new(format!(
                "cannot write {}: {e}",
                out_dir.join(name).display()
            ))
        })?;
        built.push(BuiltFile {
            name: name.clone(),
            sources: file.sources.clone(),
        });
    }

    Ok(built)
}
